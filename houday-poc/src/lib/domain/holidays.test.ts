function allHolidays(year: number): Record<string, string> {
  const result: Record<string, string> = {};
  for (let m = 1; m <= 12; m++) {
    for (const h of holidaysInMonth(`${year}-${String(m).padStart(2, '0')}`)) result[h.date] = h.name;
  }
  return result;
}

describe('日本の祝日', () => {
  for (const [year, expected] of Object.entries(OFFICIAL)) {
    it(`${year}年の祝日が公表どおり`, () => {
      expect(allHolidays(Number(year))).toEqual(expected);
    });
  }

  it('祝日でない日は null', () => {
    expect(holidayName('2026-10-19')).toBeNull();
    expect(isHoliday('2026-10-12')).toBe(true);
  });

  it('月ごとの一覧は日付順', () => {
    expect(holidaysInMonth('2026-09').map((h) => h.date)).toEqual(['2026-09-21', '2026-09-22', '2026-09-23']);
  });
});

describe('祝日付きの日付表示', () => {
  it('祝日には「祝」を付ける', () => {
    expect(formatDateWithHoliday('2026-10-12')).toBe('10/12(月・祝)');
    expect(formatDateWithHoliday('2026-10-13')).toBe('10/13(火)');
  });
});
